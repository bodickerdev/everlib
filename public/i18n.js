let lang = 'es';

export const getLang = () => lang;

export function setLang(l) {
  lang = LANGS.includes(l) ? l : 'es';
  document.documentElement.lang = lang;
}

// Idioma inicial: el guardado o, si no hay, el del navegador
export function detectLang(saved) {
  if (LANGS.includes(saved)) return saved;
  return (navigator.language || '').toLowerCase().startsWith('es') ? 'es' : 'en';
}

export function t(key, ...args) {
  const v = dict[lang][key] ?? dict.es[key] ?? key;
  return typeof v === 'function' ? v(...args) : v;
}

// Texto de datos que puede venir traducido como { es, en }
export const tr = (v) => (v && typeof v === 'object' ? v[lang] ?? v.es ?? v.en ?? '' : v ?? '');

// Aplica las traducciones a los elementos estáticos marcados con data-i18n*
export function applyStatic(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => (el.textContent = t(el.dataset.i18n)));
  for (const [attr, data] of [
    ['placeholder', 'i18nPlaceholder'],
    ['aria-label', 'i18nAria'],
    ['title', 'i18nTitle'],
  ]) {
    root.querySelectorAll(`[data-${data.replace(/[A-Z]/g, (m) => '-' + m.toLowerCase())}]`).forEach((el) => el.setAttribute(attr, t(el.dataset[data])));
  }
}
